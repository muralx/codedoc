// Package index discovers the files of a repository and keeps their rows
// in the store up to date.
package index

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"

	"github.com/cespare/xxhash/v2"

	"github.com/muralx/codedoc/internal/exclude"
	"github.com/muralx/codedoc/internal/extract/cfg"
	"github.com/muralx/codedoc/internal/gitmeta"
	"github.com/muralx/codedoc/internal/parse"
)

const (
	maxFileSize     = 2 << 20 // files above 2 MB are skipped; documents are listed without sections
	binarySniffSize = 8 << 10 // a NUL byte here marks a binary file
	generatedSniff  = 2 << 10 // generated markers are searched here
	shebangSniff    = 256     // a script's shebang line is read from here
)

// Oversized reports whether a file of size bytes is above the limit
// files are extracted up to: a document of that size is listed without
// sections, any other file is left out.
func Oversized(size int64) bool { return size > maxFileSize }

// SizeLimit is the size in bytes files are extracted up to.
func SizeLimit() int64 { return maxFileSize }

var generatedMarkers = [][]byte{
	[]byte("Code generated"), []byte("<auto-generated>"), []byte("@generated"), []byte("DO NOT EDIT"),
}

// Discovered is one file found under a repo root.
type Discovered struct {
	Path      string // slash-separated, relative to the repo root
	Lang      string // precise parser language (parse.LanguageForPath), else the config format (cfg.FormatForPath); empty when none
	Size      int64
	Mtime     int64 // Unix nanoseconds
	Hash      string
	Lines     int
	Generated bool
}

// Discover lists the indexable files under root, sorted by path. It uses
// git's view (tracked plus untracked, not ignored) and falls back to a
// directory walk when root is not a git repository. Built-in excluded
// directories (see exclude.Matcher), files matching an exclude glob, files above 2 MB
// that are no documents and
// binary files are left out, and when langs is not nil, files of a
// language or config format it lacks (see config.Repo.FileLanguages).
// Files that cannot be read (no permission, or deleted while discovery
// runs) are left out too and counted in unreadable.
func Discover(root string, exclude []string, langs map[string]bool) (files []Discovered, unreadable int, err error) {
	paths, err := indexablePaths(root, exclude)
	if err != nil {
		return nil, 0, err
	}
	for _, p := range paths {
		d, ok, err := inspect(root, p, langs)
		switch {
		case isUnreadable(err):
			unreadable++
		case err != nil:
			return nil, 0, err
		case ok:
			files = append(files, d)
		}
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files, unreadable, nil
}

// indexablePaths validates the exclude globs and lists the candidate
// paths under root that no built-in rule or glob excludes.
func indexablePaths(root string, globs []string) ([]string, error) {
	if err := exclude.ValidateGlobs(globs); err != nil {
		return nil, err
	}
	m := exclude.New(root, globs)
	paths, err := listPaths(root, m)
	if err != nil {
		return nil, err
	}
	kept := paths[:0]
	for _, p := range paths {
		if !m.Path(p, false) {
			kept = append(kept, p)
		}
	}
	return kept, nil
}

// isUnreadable reports a file that cannot be read: no permission, or
// deleted while discovery runs.
func isUnreadable(err error) bool {
	return errors.Is(err, fs.ErrPermission) || errors.Is(err, fs.ErrNotExist)
}

func listPaths(root string, m exclude.Matcher) ([]string, error) {
	paths, err := gitmeta.ListFiles(root)
	if errors.Is(err, gitmeta.ErrNotRepo) {
		return walk(root, m)
	}
	return paths, err
}

// walk lists regular files under root, pruning excluded directories.
func walk(root string, m exclude.Matcher) ([]string, error) {
	var paths []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || p == root {
			return err
		}
		rel, err := filepath.Rel(root, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		switch {
		case d.IsDir() && m.Path(rel, true):
			return filepath.SkipDir
		case d.Type().IsRegular():
			paths = append(paths, rel)
		}
		return nil
	})
	return paths, err
}

// inspect stats and reads one file. It reports false for files that are
// gone before the stat, not regular, too large (a document above the
// size limit is kept, see inspectLarge), binary or of a language langs
// leaves out (see allowed); a read error, including a file deleted after
// the stat, is returned.
func inspect(root, rel string, langs map[string]bool) (Discovered, bool, error) {
	full := filepath.Join(root, filepath.FromSlash(rel))
	info, err := os.Lstat(full)
	if errors.Is(err, fs.ErrNotExist) {
		return Discovered{}, false, nil
	}
	if err != nil {
		return Discovered{}, false, err
	}
	if !info.Mode().IsRegular() {
		return Discovered{}, false, nil
	}
	if info.Size() > maxFileSize {
		return inspectLarge(full, rel, info, langs)
	}
	data, err := os.ReadFile(full)
	if err != nil {
		return Discovered{}, false, err
	}
	if bytes.IndexByte(head(data, binarySniffSize), 0) >= 0 {
		return Discovered{}, false, nil
	}
	lang := languageOf(rel, data)
	if !allowed(langs, lang) {
		return Discovered{}, false, nil
	}
	return Discovered{
		Path: rel, Lang: lang, Size: info.Size(), Mtime: info.ModTime().UnixNano(),
		Hash: ContentHash(data), Lines: countLines(data), Generated: isGenerated(data),
	}, true, nil
}

// allowed reports whether a file of language lang is indexed under the
// repo's language selection langs: every file when langs is nil, else
// files of a selected language and files of none (manifests, READMEs).
func allowed(langs map[string]bool, lang string) bool {
	return langs == nil || lang == "" || langs[lang]
}

// languageOf returns the precise language of a file, or for a file no
// code parser handles, its document language, else its config format,
// or "".
func languageOf(rel string, data []byte) string {
	if lang := parse.LanguageForPath(rel); lang != "" {
		return lang
	}
	if lang := parse.DocLanguageForPath(rel); lang != "" {
		return lang
	}
	return cfg.FormatForPath(rel, head(data, shebangSniff))
}

// ContentHash is the content hash a file row stores.
func ContentHash(data []byte) string {
	return fmt.Sprintf("%016x", xxhash.Sum64(data))
}

func head(data []byte, n int) []byte {
	return data[:min(len(data), n)]
}

func countLines(data []byte) int {
	n := bytes.Count(data, []byte{'\n'})
	if len(data) > 0 && data[len(data)-1] != '\n' {
		n++
	}
	return n
}

func isGenerated(data []byte) bool {
	h := head(data, generatedSniff)
	for _, m := range generatedMarkers {
		if bytes.Contains(h, m) {
			return true
		}
	}
	return false
}

// inspectLarge inspects a file above the size limit: a document is
// kept, so codedoc ls lists it, but never extracted (see extractFile);
// any other file is left out. The content is streamed, not held.
func inspectLarge(full, rel string, info fs.FileInfo, langs map[string]bool) (Discovered, bool, error) {
	lang := parse.DocLanguageForPath(rel)
	if lang == "" || !allowed(langs, lang) {
		return Discovered{}, false, nil
	}
	f, err := os.Open(full)
	if err != nil {
		return Discovered{}, false, err
	}
	defer func() { _ = f.Close() }()
	sum, lines, binary, err := scanStream(f)
	if err != nil || binary {
		return Discovered{}, false, err
	}
	return Discovered{Path: rel, Lang: lang, Size: info.Size(), Mtime: info.ModTime().UnixNano(),
		Hash: fmt.Sprintf("%016x", sum), Lines: lines}, true, nil
}

// scanStream hashes a stream and counts its lines as ContentHash and
// countLines do; binary reports a NUL byte in its first binarySniffSize
// bytes.
func scanStream(r io.Reader) (sum uint64, lines int, binary bool, err error) {
	h := xxhash.New()
	buf := make([]byte, 64<<10)
	last := byte('\n')
	for total := 0; err == nil; {
		var n int
		n, err = r.Read(buf)
		chunk := buf[:n]
		if total < binarySniffSize && bytes.IndexByte(head(chunk, binarySniffSize-total), 0) >= 0 {
			return 0, 0, true, nil
		}
		total += n
		_, _ = h.Write(chunk)
		lines += bytes.Count(chunk, []byte{'\n'})
		if n > 0 {
			last = chunk[n-1]
		}
	}
	if err != io.EOF {
		return 0, 0, false, err
	}
	if last != '\n' {
		lines++
	}
	return h.Sum64(), lines, false, nil
}
